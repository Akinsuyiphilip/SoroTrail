// TestRandomScenario_DifferentSeedsProduceDifferentScenarios verifies that
// different seeds do not collapse onto the same scenario configuration.
func TestRandomScenario_DifferentSeedsProduceDifferentScenarios(t *testing.T) {
	tests := []struct {
		name  string
		seedA uint64
		seedB uint64
	}{
		{"adjacent seeds 0 and 1", 0, 1},
		{"adjacent seeds 1 and 2", 1, 2},
		{"adjacent seeds 42 and 43", 42, 43},
		{"distant seeds 100 and 200000", 100, 200000},
		{"small seed vs large seed", 999, 123456789},
		{"arbitrary seed vs max uint64", 42, math.MaxUint64},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			sA := RandomScenario(tt.seedA)
			sB := RandomScenario(tt.seedB)

			// Verify that the scenarios differ beyond just their Name string.
			assert.NotEqual(t, sA.Name, sB.Name)

			hasFunctionalDifference := sA.RetentionLedgers != sB.RetentionLedgers ||
				sA.ChainLedgers != sB.ChainLedgers ||
				sA.PageLimit != sB.PageLimit ||
				len(sA.Events) != len(sB.Events) ||
				len(sA.Faults) != len(sB.Faults) ||
				!reflect.DeepEqual(sA.Events, sB.Events) ||
				!reflect.DeepEqual(sA.Faults, sB.Faults)

			assert.True(t, hasFunctionalDifference,
				"seed %d and seed %d must produce functionally distinct scenarios", tt.seedA, tt.seedB)
		})
	}
}

// TestGenerateRandom_DocumentedBounds asserts that every field in the
// generated scenario strictly conforms to the documented bounds:
//   - Retention window: 10-500 ledgers
//   - Events: 5-50 events placed at ledgers 1 to maxLedger
//   - ChainLedgers: 20-219 ledgers
//   - PageLimit: 10-99
//   - Faults: 0-3 faults, each with valid call indices (1-5) or afterStep (1-5)
func TestGenerateRandom_DocumentedBounds(t *testing.T) {
	// Table of boundary and representative seeds.
	seeds := []struct {
		name string
		seed uint64
	}{
		{"seed 0", 0},
		{"seed 1", 1},
		{"seed 2", 2},
		{"seed 7", 7},
		{"seed 42", 42},
		{"seed 100", 100},
		{"seed 999", 999},
		{"seed 12345", 12345},
		{"max uint32", math.MaxUint32},
		{"max uint64", math.MaxUint64},
	}

	for _, tt := range seeds {
		t.Run(tt.name, func(t *testing.T) {
			s := RandomScenario(tt.seed)
			assertScenarioWithinDocumentedBounds(t, s)
		})
	}

	// Also sample across a sequence of 200 pseudo-random seeds to
	// exercise broader PRNG states against all boundary conditions.
	t.Run("sample over 200 seeds", func(t *testing.T) {
		for seed := uint64(1); seed <= 200; seed++ {
			s := RandomScenario(seed * 7919) // prime multiplier
			assertScenarioWithinDocumentedBounds(t, s)
		}
	})
}

// assertScenarioWithinDocumentedBounds checks all documented bounds for a scenario.
func assertScenarioWithinDocumentedBounds(t *testing.T, s Scenario) {
	t.Helper()

	assert.Equal(t, "Randomized scenario generated by PRNG.", s.Description)

	// Documented: 10-500 retention ledgers.
	assert.GreaterOrEqual(t, s.RetentionLedgers, uint32(10), "retention must be >= 10")
	assert.LessOrEqual(t, s.RetentionLedgers, uint32(500), "retention must be <= 500")

	// Documented: 20 + rng.IntN(200) -> 20-219 chain ledgers.
	assert.GreaterOrEqual(t, s.ChainLedgers, uint32(20), "chain ledgers must be >= 20")
	assert.LessOrEqual(t, s.ChainLedgers, uint32(219), "chain ledgers must be <= 219")

	// Documented: 10 + rng.IntN(90) -> 10-99 page limit.
	assert.GreaterOrEqual(t, s.PageLimit, uint(10), "page limit must be >= 10")
	assert.LessOrEqual(t, s.PageLimit, uint(99), "page limit must be <= 99")

	// Documented: 5-50 events.
	assert.GreaterOrEqual(t, len(s.Events), 5, "event count must be >= 5")
	assert.LessOrEqual(t, len(s.Events), 50, "event count must be <= 50")

	// Each event must be placed at a ledger between 1 and s.ChainLedgers.
	for i, ev := range s.Events {
		assert.GreaterOrEqual(t, ev.Ledger, uint32(1), "event %d ledger must be >= 1", i)
		assert.LessOrEqual(t, ev.Ledger, s.ChainLedgers, "event %d ledger must be <= chainLedgers", i)
		assert.NotEmpty(t, ev.ContractID, "event %d contract ID must not be empty", i)
	}

	// Documented: 0-3 faults.
	assert.GreaterOrEqual(t, len(s.Faults), 0, "fault count must be >= 0")
	assert.LessOrEqual(t, len(s.Faults), 3, "fault count must be <= 3")

	for i, f := range s.Faults {
		switch f.Kind {
		case FaultTimeout, FaultRateLimit, FaultOutOfRange:
			assert.GreaterOrEqual(t, f.CallIndex, 1, "fault %d call index must be >= 1", i)
			assert.LessOrEqual(t, f.CallIndex, 5, "fault %d call index must be <= 5", i)
		case FaultCrash:
			assert.GreaterOrEqual(t, f.AfterStep, 1, "crash fault %d afterStep must be >= 1", i)
			assert.LessOrEqual(t, f.AfterStep, 5, "crash fault %d afterStep must be <= 5", i)
		default:
			t.Fatalf("unexpected fault kind %q in random scenario", f.Kind)
		}
	}
}

