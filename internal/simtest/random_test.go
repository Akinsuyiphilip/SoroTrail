// TestRandomScenario_IdenticalSeedAssertsReproducibility verifies that
// calling RandomScenario with the exact same seed produces identical
// scenario configurations every time. Deterministic reproducibility is
// essential so any failure caught by randomized testing can be replayed.
func TestRandomScenario_IdenticalSeedAssertsReproducibility(t *testing.T) {
	tests := []struct {
		name string
		seed uint64
	}{
		{"zero seed", 0},
		{"unit seed 1", 1},
		{"arbitrary seed 42", 42},
		{"arbitrary seed 999", 999},
		{"large seed", 123456789},
		{"max uint32 seed", math.MaxUint32},
		{"max uint64 seed", math.MaxUint64},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			first := RandomScenario(tt.seed)
			second := RandomScenario(tt.seed)

			// Assert full structural equality across all fields.
			assert.Equal(t, first, second,
				"calling RandomScenario twice with seed %d must produce identical scenarios", tt.seed)
		})
	}
}

