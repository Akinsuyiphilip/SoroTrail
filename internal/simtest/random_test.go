// TestRandomScenario_SeedReportedOnFailure verifies that the scenario name
// embeds the seed in a machine-parseable and human-readable format
// ("random_<seed>") so test runners can print and report the seed upon
// failure, enabling deterministic reproduction of regressions.
func TestRandomScenario_SeedReportedOnFailure(t *testing.T) {
	tests := []struct {
		name string
		seed uint64
	}{
		{"seed 0", 0},
		{"seed 42", 42},
		{"seed 999", 999},
		{"seed 123456789", 123456789},
		{"max uint64", math.MaxUint64},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s := RandomScenario(tt.seed)

			// The seed must be encoded in the scenario name.
			expectedName := fmt.Sprintf("random_%d", tt.seed)
			assert.Equal(t, expectedName, s.Name)

			// Verify the seed is parseable from the scenario name.
			var parsedSeed uint64
			n, err := fmt.Sscanf(s.Name, "random_%d", &parsedSeed)
			require.NoError(t, err, "scenario name must follow random_<seed> format")
			assert.Equal(t, 1, n)
			assert.Equal(t, tt.seed, parsedSeed)

			// Verify that an error message constructed from the failure
			// report contains the reproduction seed.
			failureMsg := fmt.Sprintf("scenario %s failed, re-run with seed %d", s.Name, tt.seed)
			assert.Contains(t, failureMsg, fmt.Sprintf("%d", tt.seed))
		})
	}
}

// dupStore wraps mockStore and appends an extra duplicate event to QueryEvents
// results, enabling testing of the oracle's duplicate detection invariant.
type dupStore struct {
	*mockStore
	dup store.Event
}

func (d *dupStore) QueryEvents(ctx context.Context, f store.EventFilter) ([]store.Event, string, error) {
	events, cur, err := d.mockStore.QueryEvents(ctx, f)
	if err != nil {
		return nil, "", err
	}
	return append(events, d.dup), cur, nil
}

// failingStore returns an error on QueryEvents to test StoredCount error handling.
type failingStore struct {
	*mockStore
	err error
}

func (f *failingStore) QueryEvents(ctx context.Context, filter store.EventFilter) ([]store.Event, string, error) {
	return nil, "", f.err
}

// TestOracle_AssertsInvariant covers all oracle helper methods
// (StoredCount, FetchableCount, LegitimatelyLostEvents, DrainGaps,
// RecordReclamp, Verify) and asserts that the oracle validates systemic
// invariants rather than matching a fixed hardcoded output.
func TestOracle_AssertsInvariant(t *testing.T) {
	now := time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC)
	ctx := context.Background()

	t.Run("stored count matches store contents", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		oracle := NewOracle(chain)

		st := newMockStore()
		count, err := oracle.StoredCount(ctx, st)
		require.NoError(t, err)
		assert.Equal(t, 0, count)

		// Insert 3 events.
		_, err = st.UpsertEvents(ctx, []store.Event{
			{ID: "0000000005-000000000", Ledger: 5, ContractID: "CAAA"},
			{ID: "0000000006-000000000", Ledger: 6, ContractID: "CAAA"},
			{ID: "0000000007-000000000", Ledger: 7, ContractID: "CAAA"},
		})
		require.NoError(t, err)

		count, err = oracle.StoredCount(ctx, st)
		require.NoError(t, err)
		assert.Equal(t, 3, count)
	})

	t.Run("stored count propagates store query errors", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		oracle := NewOracle(chain)

		expectedErr := fmt.Errorf("connection refused")
		fst := &failingStore{mockStore: newMockStore(), err: expectedErr}

		count, err := oracle.StoredCount(ctx, fst)
		require.Error(t, err)
		assert.ErrorIs(t, err, expectedErr)
		assert.Equal(t, 0, count)
	})

	t.Run("invariant holds when all fetchable events are stored exactly once", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		ev1 := BuildEvent("0000000005-000000000", 5, "CAAAA")
		ev2 := BuildEvent("0000000010-000000000", 10, "CAAAA")
		chain.AddEvents(5, ev1)
		chain.AddEvents(10, ev2)

		oracle := NewOracle(chain)
		assert.Equal(t, 2, oracle.FetchableCount())
		assert.Empty(t, oracle.LegitimatelyLostEvents())

		st := newMockStore()
		_, err := st.UpsertEvents(ctx, []store.Event{
			{ID: ev1.ID, Ledger: 5, ContractID: "CAAAA"},
			{ID: ev2.ID, Ledger: 10, ContractID: "CAAAA"},
		})
		require.NoError(t, err)

		// Invariant: StoredCount equals FetchableCount and Verify succeeds.
		storedCount, err := oracle.StoredCount(ctx, st)
		require.NoError(t, err)
		assert.Equal(t, oracle.FetchableCount(), storedCount)
		assert.NoError(t, oracle.Verify(ctx, st))
	})

	t.Run("invariant holds when legitimately lost events are excluded from store", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 10)
		evLost := BuildEvent("0000000005-000000000", 5, "CAAAA")
		evRetained := BuildEvent("0000000095-000000000", 95, "CAAAA")
		chain.AddEvents(5, evLost)
		chain.AddEvents(95, evRetained)

		oracle := NewOracle(chain)
		// Record legitimate retention gap for [2, 90).
		oracle.RecordReclamp(2, 90)

		// Invariant: partition of total events between fetchable and lost.
		assert.Equal(t, 1, oracle.FetchableCount())
		assert.Equal(t, []string{evLost.ID}, oracle.LegitimatelyLostEvents())

		// Store contains only the retained event.
		st := newMockStore()
		_, err := st.UpsertEvents(ctx, []store.Event{
			{ID: evRetained.ID, Ledger: 95, ContractID: "CAAAA"},
		})
		require.NoError(t, err)

		assert.NoError(t, oracle.Verify(ctx, st))
	})

	t.Run("invariant violation when fetchable event is missing from store", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		ev1 := BuildEvent("0000000005-000000000", 5, "CAAAA")
		ev2 := BuildEvent("0000000010-000000000", 10, "CAAAA")
		chain.AddEvents(5, ev1)
		chain.AddEvents(10, ev2)

		oracle := NewOracle(chain)
		st := newMockStore()
		// Only store ev1; ev2 is missing.
		_, err := st.UpsertEvents(ctx, []store.Event{
			{ID: ev1.ID, Ledger: 5, ContractID: "CAAAA"},
		})
		require.NoError(t, err)

		err = oracle.Verify(ctx, st)
		require.Error(t, err)
		assert.Contains(t, err.Error(), fmt.Sprintf("fetchable event %s is missing from the store", ev2.ID))
	})

	t.Run("invariant violation when event appears duplicate times in store", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		ev1 := BuildEvent("0000000005-000000000", 5, "CAAAA")
		chain.AddEvents(5, ev1)

		oracle := NewOracle(chain)
		baseStore := newMockStore()
		storedEv := store.Event{ID: ev1.ID, Ledger: 5, ContractID: "CAAAA"}
		_, err := baseStore.UpsertEvents(ctx, []store.Event{storedEv})
		require.NoError(t, err)

		dst := &dupStore{mockStore: baseStore, dup: storedEv}
		err = oracle.Verify(ctx, dst)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "appears 2 times in the store (expected 1)")
	})

	t.Run("invariant violation when spurious event is present in store", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		ev1 := BuildEvent("0000000005-000000000", 5, "CAAAA")
		chain.AddEvents(5, ev1)

		oracle := NewOracle(chain)
		st := newMockStore()
		_, err := st.UpsertEvents(ctx, []store.Event{
			{ID: ev1.ID, Ledger: 5, ContractID: "CAAAA"},
			{ID: "spurious-not-on-chain", Ledger: 5, ContractID: "CAAAA"},
		})
		require.NoError(t, err)

		err = oracle.Verify(ctx, st)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "spurious event spurious-not-on-chain in store (not in chain)")
	})

	t.Run("invariant violation when legitimate loss occurs but no warnings recorded", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 10)
		ev1 := BuildEvent("0000000005-000000000", 5, "CAAAA")
		chain.AddEvents(5, ev1)

		oracle := NewOracle(chain)
		// Directly populate legitimatelyLost with warnings = 0 to simulate silent data loss.
		oracle.legitimatelyLost = append(oracle.legitimatelyLost, ledgerRange{from: 2, to: 10})
		oracle.warnings = 0

		st := newMockStore()
		err := oracle.Verify(ctx, st)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "silent data loss")
	})

	t.Run("tolerates already persisted event in legitimate loss range", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 10)
		ev := BuildEvent("0000000005-000000000", 5, "CAAAA")
		chain.AddEvents(5, ev)

		oracle := NewOracle(chain)
		oracle.RecordReclamp(2, 10) // ledger 5 is now in a lost range

		// Event was already persisted before the gap happened.
		st := newMockStore()
		_, err := st.UpsertEvents(ctx, []store.Event{
			{ID: ev.ID, Ledger: 5, ContractID: "CAAAA"},
		})
		require.NoError(t, err)

		// Invariant: events in lost range that are already persisted are not treated as spurious errors.
		assert.NoError(t, oracle.Verify(ctx, st))
	})

	t.Run("record reclamp ignores non-gap requests", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 100)
		ev := BuildEvent("0000000005-000000000", 5, "CAAAA")
		chain.AddEvents(5, ev)

		oracle := NewOracle(chain)
		// requested >= oldest is not a gap.
		oracle.RecordReclamp(10, 10)
		oracle.RecordReclamp(15, 10)

		assert.Equal(t, 1, oracle.FetchableCount())
		assert.Empty(t, oracle.LegitimatelyLostEvents())
	})

	t.Run("drain gaps consumes recorded gaps from virtual chain", func(t *testing.T) {
		clock := NewVirtualClock(now)
		chain := NewVirtualChain(clock, now, 10)
		chain.AdvanceTo(100) // oldestRetained is 90

		evLost := BuildEvent("0000000050-000000000", 50, "CAAAA")
		evRetained := BuildEvent("0000000095-000000000", 95, "CAAAA")
		chain.AddEvents(50, evLost)
		chain.AddEvents(95, evRetained)

		// Trigger an out-of-range error on the chain to record a gap.
		_, err := chain.GetEvents(ctx, rpc.GetEventsRequest{StartLedger: 50})
		require.Error(t, err)

		oracle := NewOracle(chain)
		assert.Equal(t, 2, oracle.FetchableCount(), "before DrainGaps, all events are considered fetchable")

		oracle.DrainGaps()
		assert.Equal(t, 1, oracle.FetchableCount(), "after DrainGaps, gap ledgers are classified as lost")
		assert.Equal(t, []string{evLost.ID}, oracle.LegitimatelyLostEvents())
	})
}

// TestOracle_RandomScenariosInvariantValidation verifies the oracle invariant
// across scenarios generated from multiple random seeds. For each scenario,
// regardless of randomized event placement, the invariant must hold:
//   - StoredCount == FetchableCount
//   - FetchableCount + len(LegitimatelyLostEvents) == total events
//   - Verify passes when the store contains all fetchable events
//   - Verify fails if any fetchable event is removed
func TestOracle_RandomScenariosInvariantValidation(t *testing.T) {
	seeds := []uint64{7, 42, 101, 777, 12345}
	now := time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC)
	ctx := context.Background()

	for _, seed := range seeds {
		t.Run(fmt.Sprintf("seed_%d", seed), func(t *testing.T) {
			scenario := RandomScenario(seed)
			clock := NewVirtualClock(now)
			chain := NewVirtualChain(clock, now, scenario.RetentionLedgers)

			st := newMockStore()
			var chainEvs []store.Event
			for i, ep := range scenario.Events {
				id := fmt.Sprintf("%010d-%09d", ep.Ledger, i)
				ev := BuildEvent(id, ep.Ledger, ep.ContractID)
				chain.AddEvents(ep.Ledger, ev)
				chainEvs = append(chainEvs, store.Event{
					ID:         id,
					Ledger:     int64(ep.Ledger),
					ContractID: ep.ContractID,
				})
			}

			oracle := NewOracle(chain)

			// Invariant 1: without gaps, all generated events are fetchable.
			assert.Equal(t, len(scenario.Events), oracle.FetchableCount())
			assert.Empty(t, oracle.LegitimatelyLostEvents())

			// Store all events.
			_, err := st.UpsertEvents(ctx, chainEvs)
			require.NoError(t, err)

			// Invariant 2: stored count equals fetchable count.
			storedCount, err := oracle.StoredCount(ctx, st)
			require.NoError(t, err)
			assert.Equal(t, oracle.FetchableCount(), storedCount)

			// Invariant 3: Verify succeeds.
			require.NoError(t, oracle.Verify(ctx, st))

			// Invariant 4: removing any fetchable event violates completeness.
			if len(chainEvs) > 0 {
				corruptStore := newMockStore()
				_, err = corruptStore.UpsertEvents(ctx, chainEvs[1:])
				require.NoError(t, err)

				err = oracle.Verify(ctx, corruptStore)
				require.Error(t, err, "oracle must detect missing fetchable event")
				assert.Contains(t, err.Error(), fmt.Sprintf("fetchable event %s is missing from the store", chainEvs[0].ID))
			}
		})
	}
}
